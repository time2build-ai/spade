"""Tiny workflow-evaluation harness.

Each *scenario* is a function that drives the REAL Spade API/domain (a fresh,
isolated SQLite DB per scenario) through a product workflow and records pass/fail
checks. The runner aggregates them into a report — this is a level above the unit
tests: it asks "do the end-to-end workflows actually work?".
"""

from __future__ import annotations

import os
import tempfile
import traceback
from dataclasses import dataclass, field


@dataclass
class Check:
    ok: bool
    label: str
    detail: str = ""


@dataclass
class Scenario:
    suite: str
    name: str
    checks: list[Check] = field(default_factory=list)
    error: str | None = None

    @property
    def passed(self) -> bool:
        return self.error is None and all(c.ok for c in self.checks)


class Ctx:
    """Passed to each scenario. `check(cond, label, detail)` records a result."""

    def __init__(self, scenario: Scenario):
        self.s = scenario

    def check(self, cond: bool, label: str, detail: str = "") -> bool:
        self.s.checks.append(Check(bool(cond), label, "" if cond else detail))
        return bool(cond)

    def eq(self, got, want, label: str) -> bool:
        return self.check(got == want, label, f"got {got!r}, want {want!r}")


def _fresh_db() -> None:
    """Point the app at a brand-new empty DB (full isolation per scenario)."""
    from tui_pilot import db

    os.environ["TUI_PILOT_HOME"] = tempfile.mkdtemp(prefix="spade-eval-")
    db.reset()


def run(scenarios: list, *, report_path: str | None = None) -> bool:
    """Run all scenarios; print a report; optionally write markdown. Returns
    True iff every scenario passed."""
    results: list[Scenario] = []
    for suite, name, fn in scenarios:
        sc = Scenario(suite, name)
        try:
            _fresh_db()
            fn(Ctx(sc))
        except Exception:  # a scenario that throws is a failed workflow
            sc.error = traceback.format_exc()
        results.append(sc)

    _print_report(results)
    if report_path:
        _write_markdown(results, report_path)
    return all(s.passed for s in results)


def _print_report(results: list[Scenario]) -> None:
    by_suite: dict[str, list[Scenario]] = {}
    for s in results:
        by_suite.setdefault(s.suite, []).append(s)

    total_checks = sum(len(s.checks) for s in results)
    passed_checks = sum(1 for s in results for c in s.checks if c.ok)
    passed_scen = sum(1 for s in results if s.passed)

    print("\n" + "=" * 74)
    print("  SPADE WORKFLOW EVALUATIONS")
    print("=" * 74)
    for suite, scens in by_suite.items():
        print(f"\n▌ {suite}")
        for s in scens:
            mark = "✓" if s.passed else "✗"
            n_ok = sum(1 for c in s.checks if c.ok)
            print(f"  {mark} {s.name}  ({n_ok}/{len(s.checks)} checks)")
            if not s.passed:
                for c in s.checks:
                    if not c.ok:
                        print(f"      ✗ {c.label} — {c.detail}")
                if s.error:
                    last = s.error.strip().splitlines()[-1]
                    print(f"      ! {last}")
    print("\n" + "-" * 74)
    print(f"  Scenarios: {passed_scen}/{len(results)} passed   "
          f"Checks: {passed_checks}/{total_checks} passed")
    print("=" * 74)


def _write_markdown(results: list[Scenario], path: str) -> None:
    by_suite: dict[str, list[Scenario]] = {}
    for s in results:
        by_suite.setdefault(s.suite, []).append(s)
    passed_scen = sum(1 for s in results if s.passed)
    total_checks = sum(len(s.checks) for s in results)
    passed_checks = sum(1 for s in results for c in s.checks if c.ok)

    lines = [
        "# Spade workflow evaluations — report",
        "",
        f"**{passed_scen}/{len(results)} scenarios** and "
        f"**{passed_checks}/{total_checks} checks** passed.",
        "",
        "Each scenario drives the real API/domain (isolated DB) through a product "
        "workflow. Generated by `evals/run_evals.py`.",
        "",
    ]
    for suite, scens in by_suite.items():
        lines.append(f"## {suite}")
        lines.append("")
        for s in scens:
            mark = "✅" if s.passed else "❌"
            n_ok = sum(1 for c in s.checks if c.ok)
            lines.append(f"### {mark} {s.name} ({n_ok}/{len(s.checks)})")
            for c in s.checks:
                box = "- [x]" if c.ok else "- [ ]"
                extra = "" if c.ok else f" — {c.detail}"
                lines.append(f"{box} {c.label}{extra}")
            if s.error:
                last = s.error.strip().splitlines()[-1]
                lines.append(f"> error: `{last}`")
            lines.append("")
    with open(path, "w") as fh:
        fh.write("\n".join(lines))
